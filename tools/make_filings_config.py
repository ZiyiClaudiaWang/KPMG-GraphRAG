"""
Rebuild extraction_pipeline/config/filings.yaml from the Data team database.

Keeps the rule written in the current file: every 10-K and 10-Q of the ten companies whose
validation_status is "passed". Filings that fail the rule (another status, or no sections yet)
are left out and listed in the file's header comment, so the exclusions stay visible.

Run from tools/ (it reads .env.aws there):
    uv run make_filings_config.py                      # print to the screen only
    uv run make_filings_config.py --write              # overwrite ../extraction_pipeline/config/filings.yaml
    uv run make_filings_config.py --since 2024-01-01   # filing-date lower bound (default: all)
"""

from __future__ import annotations

import argparse
from datetime import date
from pathlib import Path

from graphrag_data import connect, find_filings

TICKERS = ["AAPL", "CASY", "MCK", "MDT", "MSFT", "MU", "NKE", "NTAP", "PH", "TTWO"]
OUT = Path(__file__).resolve().parent.parent / "extraction_pipeline" / "config" / "filings.yaml"


def build(since: str | None) -> str:
    with connect() as conn:
        f = find_filings(conn, tickers=TICKERS, since=since)
    if f.empty:
        raise SystemExit("No filings found for the ten companies.")
    f = f[f.form.isin(["10-K", "10-Q"])].copy()
    f["rpe"] = f.reporting_period_end.astype(str)

    keep = f[(f.validation_status == "passed") & (f.n_sections > 0)]
    left_out = f.drop(keep.index)
    keep = keep.sort_values(["ticker", "rpe", "accession_number"])

    head = [
        "# Filings for the ten companies: every 10-K and 10-Q loaded in the Data team",
        f"# database on {date.today().isoformat()} whose validation_status is \"passed\""
        + (f", filed on or after {since}." if since else "."),
        "# Generated by tools/make_filings_config.py; rerun it rather than editing by hand.",
    ]
    if left_out.empty:
        head.append("# Left out: none.")
    else:
        head.append("# Left out:")
        for r in left_out.sort_values(["ticker", "rpe"]).itertuples():
            why = r.validation_status if r.n_sections > 0 else f"{r.validation_status}, no sections"
            head.append(f"#   {r.ticker} {r.form} {r.accession_number} ({why})")
    head += [
        "# The fetch step exports each one to <data_dir>/sections/<TICKER>_<accession>.jsonl",
        "# (one line per section). Within a company, filings are in period order.",
        "",
        "filings:",
    ]

    rows = []
    for r in keep.itertuples():
        t = f"{r.ticker},".ljust(5)
        rows.append(
            f'  - {{ticker: {t} cik: "{r.cik}", form: {r.form}, '
            f'reporting_period_end: "{r.rpe}", accession: "{r.accession_number}"}}'
        )

    summary = keep.groupby(["ticker", "form"]).size().unstack(fill_value=0).reindex(TICKERS).fillna(0).astype(int)
    print(summary.to_string())
    print(f"\n{len(keep)} filings kept, {len(left_out)} left out.\n")
    return "\n".join(head + rows) + "\n"


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--since", help="filing date from, YYYY-MM-DD")
    p.add_argument("--write", action="store_true", help=f"overwrite {OUT}")
    a = p.parse_args()
    text = build(a.since)
    if a.write:
        OUT.write_text(text, encoding="utf-8")
        print(f"Wrote {OUT}")
    else:
        print(text)


if __name__ == "__main__":
    main()
